USE ROLE SYSADMIN;
USE DATABASE HORIZON_DEMO_DB;
USE SCHEMA HEALTHCARE;
USE WAREHOUSE MY_WH;

-- Row access policy (applied after DT creation)
CREATE OR REPLACE ROW ACCESS POLICY DEPARTMENT_ROW_POLICY
AS (department_val VARCHAR) RETURNS BOOLEAN ->
  CASE
    WHEN IS_ROLE_IN_SESSION('SYSADMIN') THEN TRUE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ADMIN') THEN TRUE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_COMPLIANCE') THEN TRUE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ANALYST') THEN TRUE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_CLINICAL') THEN department_val = 'CARDIOLOGY'
    ELSE FALSE
  END;

ALTER TABLE PATIENTS ADD ROW ACCESS POLICY DEPARTMENT_ROW_POLICY ON (DEPARTMENT);

-- Join policy
CREATE OR REPLACE JOIN POLICY PATIENT_JOIN_POLICY
AS () RETURNS JOIN_CONSTRAINT ->
  CASE
    WHEN IS_ROLE_IN_SESSION('SYSADMIN') THEN JOIN_CONSTRAINT(JOIN_REQUIRED => FALSE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ADMIN') THEN JOIN_CONSTRAINT(JOIN_REQUIRED => FALSE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_COMPLIANCE') THEN JOIN_CONSTRAINT(JOIN_REQUIRED => FALSE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_CLINICAL') THEN JOIN_CONSTRAINT(JOIN_REQUIRED => FALSE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ANALYST') THEN JOIN_CONSTRAINT(JOIN_REQUIRED => TRUE)
    ELSE JOIN_CONSTRAINT(JOIN_REQUIRED => FALSE)
  END;

ALTER TABLE PATIENTS SET JOIN POLICY PATIENT_JOIN_POLICY;

-- Aggregation policy
CREATE OR REPLACE AGGREGATION POLICY MIN_GROUP_SIZE_POLICY
AS () RETURNS AGGREGATION_CONSTRAINT ->
  CASE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ADMIN') THEN NO_AGGREGATION_CONSTRAINT()
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_COMPLIANCE') THEN NO_AGGREGATION_CONSTRAINT()
    WHEN IS_ROLE_IN_SESSION('SYSADMIN') THEN NO_AGGREGATION_CONSTRAINT()
    ELSE AGGREGATION_CONSTRAINT(MIN_GROUP_SIZE => 5)
  END;

ALTER TABLE BILLING SET AGGREGATION POLICY MIN_GROUP_SIZE_POLICY;
