-- Custom DMFs
CREATE OR REPLACE DATA METRIC FUNCTION INVALID_SSN_COUNT(ARG_T TABLE(ARG_C VARCHAR))
RETURNS NUMBER AS
$$
  SELECT COUNT(*) FROM ARG_T
  WHERE ARG_C IS NOT NULL AND NOT REGEXP_LIKE(ARG_C, '^[0-9]{3}-[0-9]{2}-[0-9]{4}$')
$$;

CREATE OR REPLACE DATA METRIC FUNCTION INVALID_PHONE_COUNT(ARG_T TABLE(ARG_C VARCHAR))
RETURNS NUMBER AS
$$
  SELECT COUNT(*) FROM ARG_T
  WHERE ARG_C IS NOT NULL AND NOT REGEXP_LIKE(ARG_C, '^\([0-9]{3}\) [0-9]{3}-[0-9]{4}$')
$$;

ALTER TABLE PATIENTS ADD DATA METRIC FUNCTION INVALID_SSN_COUNT ON (SSN);
ALTER TABLE PATIENTS ADD DATA METRIC FUNCTION INVALID_PHONE_COUNT ON (PHONE);

