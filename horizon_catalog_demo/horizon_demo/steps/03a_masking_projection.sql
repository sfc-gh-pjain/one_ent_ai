USE ROLE SYSADMIN;
USE DATABASE HORIZON_DEMO_DB;
USE SCHEMA HEALTHCARE;
USE WAREHOUSE MY_WH;

-- Masking policy (tag-based)
CREATE OR REPLACE MASKING POLICY PII_TAG_MASK AS (val VARCHAR)
RETURNS VARCHAR ->
  CASE
    WHEN IS_ROLE_IN_SESSION('SYSADMIN') THEN val
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_COMPLIANCE') THEN val
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ADMIN') THEN val
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_CLINICAL') THEN
      CASE SYSTEM$GET_TAG_ON_CURRENT_COLUMN('HORIZON_DEMO_DB.HEALTHCARE.PII_LEVEL')
        WHEN 'HIGH' THEN '***-**-' || RIGHT(val, 4)
        ELSE val
      END
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ANALYST') THEN
      CASE SYSTEM$GET_TAG_ON_CURRENT_COLUMN('HORIZON_DEMO_DB.HEALTHCARE.PII_LEVEL')
        WHEN 'HIGH' THEN '***-**-****'
        WHEN 'MEDIUM' THEN '********'
        ELSE val
      END
    ELSE '********'
  END;

ALTER TABLE PATIENTS MODIFY COLUMN SSN SET MASKING POLICY PII_TAG_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN EMAIL SET MASKING POLICY PII_TAG_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN PHONE SET MASKING POLICY PII_TAG_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN ADDRESS_LINE1 SET MASKING POLICY PII_TAG_MASK;

-- Projection policy
CREATE OR REPLACE PROJECTION POLICY PRESCRIPTION_PROJECTION_POLICY
AS () RETURNS PROJECTION_CONSTRAINT ->
  CASE
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ADMIN') THEN PROJECTION_CONSTRAINT(ALLOW => TRUE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_COMPLIANCE') THEN PROJECTION_CONSTRAINT(ALLOW => TRUE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_CLINICAL') THEN PROJECTION_CONSTRAINT(ALLOW => TRUE)
    WHEN IS_ROLE_IN_SESSION('SYSADMIN') THEN PROJECTION_CONSTRAINT(ALLOW => TRUE)
    WHEN IS_ROLE_IN_SESSION('HORIZON_DEMO_ANALYST') THEN PROJECTION_CONSTRAINT(ALLOW => FALSE)
    ELSE PROJECTION_CONSTRAINT(ALLOW => FALSE)
  END;

ALTER TABLE PRESCRIPTIONS MODIFY COLUMN MEDICATION_NAME SET PROJECTION POLICY PRESCRIPTION_PROJECTION_POLICY;
