-- ============================================================
-- 4. Cross-System Governance Inventory View
-- Single pane of glass across all source systems
-- ============================================================

CREATE OR REPLACE VIEW GOVERNANCE_INVENTORY AS
WITH tagged_objects AS (
    SELECT
        OBJECT_DATABASE,
        OBJECT_SCHEMA,
        OBJECT_NAME,
        TAG_NAME,
        TAG_VALUE
    FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
    WHERE TAG_DATABASE = 'DEMO'
      AND TAG_SCHEMA = 'HEALTHCARE_DEMO'
      AND TAG_NAME IN ('SOURCE_SYSTEM', 'INTEGRATION_PATTERN', 'DATA_FRESHNESS_SLA',
                       'DATA_DOMAIN', 'DATA_QUALITY_STATUS', 'DATA_OWNER', 'COMPLIANCE_FRAMEWORK')
      AND DOMAIN = 'TABLE'
)
SELECT
    OBJECT_DATABASE || '.' || OBJECT_SCHEMA || '.' || OBJECT_NAME AS FULLY_QUALIFIED_NAME,
    OBJECT_SCHEMA AS SCHEMA_NAME,
    OBJECT_NAME AS TABLE_NAME,
    MAX(CASE WHEN TAG_NAME = 'SOURCE_SYSTEM' THEN TAG_VALUE END) AS SOURCE_SYSTEM,
    MAX(CASE WHEN TAG_NAME = 'INTEGRATION_PATTERN' THEN TAG_VALUE END) AS INTEGRATION_PATTERN,
    MAX(CASE WHEN TAG_NAME = 'DATA_FRESHNESS_SLA' THEN TAG_VALUE END) AS FRESHNESS_SLA,
    MAX(CASE WHEN TAG_NAME = 'DATA_DOMAIN' THEN TAG_VALUE END) AS DATA_DOMAIN,
    MAX(CASE WHEN TAG_NAME = 'DATA_QUALITY_STATUS' THEN TAG_VALUE END) AS DQ_STATUS,
    MAX(CASE WHEN TAG_NAME = 'DATA_OWNER' THEN TAG_VALUE END) AS OWNER,
    MAX(CASE WHEN TAG_NAME = 'COMPLIANCE_FRAMEWORK' THEN TAG_VALUE END) AS COMPLIANCE
FROM tagged_objects
GROUP BY 1, 2, 3
ORDER BY SOURCE_SYSTEM, SCHEMA_NAME, TABLE_NAME;

-- ============================================================
-- 5. Source System Summary (for exec dashboards)
-- ============================================================

CREATE OR REPLACE VIEW GOVERNANCE_SOURCE_SUMMARY AS
SELECT
    MAX(CASE WHEN TAG_NAME = 'SOURCE_SYSTEM' THEN TAG_VALUE END) AS SOURCE_SYSTEM,
    COUNT(DISTINCT OBJECT_NAME) AS TABLE_COUNT,
    LISTAGG(DISTINCT OBJECT_SCHEMA, ', ') AS SCHEMAS
FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
WHERE TAG_DATABASE = 'DEMO'
  AND TAG_SCHEMA = 'HEALTHCARE_DEMO'
  AND TAG_NAME = 'SOURCE_SYSTEM'
  AND DOMAIN = 'TABLE'
GROUP BY OBJECT_DATABASE
ORDER BY TABLE_COUNT DESC;

-- ============================================================
-- 6. Compliance Coverage Report
-- Shows which tables are under regulatory governance
-- ============================================================

CREATE OR REPLACE VIEW GOVERNANCE_COMPLIANCE_COVERAGE AS
SELECT
    OBJECT_SCHEMA,
    OBJECT_NAME,
    TAG_VALUE AS COMPLIANCE_FRAMEWORK,
    CASE
        WHEN TAG_VALUE IN ('HIPAA', 'SOX', 'GDPR', 'PCI_DSS') THEN 'REGULATED'
        ELSE 'UNREGULATED'
    END AS REGULATION_STATUS
FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
WHERE TAG_DATABASE = 'DEMO'
  AND TAG_SCHEMA = 'HEALTHCARE_DEMO'
  AND TAG_NAME = 'COMPLIANCE_FRAMEWORK'
  AND DOMAIN = 'TABLE'
ORDER BY COMPLIANCE_FRAMEWORK, OBJECT_SCHEMA;

