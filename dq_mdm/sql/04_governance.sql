-- ============================================================
-- Governance: Tags, Masking Policies, Row Access Policies
-- Healthcare Commercial Analytics Pipeline
-- ============================================================
-- Idempotent — safe to re-run

USE ROLE SYSADMIN;
USE WAREHOUSE MY_WH;
USE SCHEMA DEMO.HEALTHCARE_DEMO;

-- ============================================================
-- 1. Create Tags
-- ============================================================

CREATE TAG IF NOT EXISTS SENSITIVITY_LEVEL
    ALLOWED_VALUES 'PII', 'PHI', 'PUBLIC', 'INTERNAL';

CREATE TAG IF NOT EXISTS DATA_DOMAIN
    ALLOWED_VALUES 'COMMERCIAL', 'CLINICAL', 'FINANCE', 'OPERATIONS';

CREATE TAG IF NOT EXISTS DATA_QUALITY_STATUS
    ALLOWED_VALUES 'CERTIFIED', 'IN_REVIEW', 'QUARANTINED';

CREATE TAG IF NOT EXISTS DATA_OWNER
    COMMENT = 'Team or individual responsible for this data asset';

-- ============================================================
-- 2. Apply Tags to Tables
-- ============================================================

-- Table-level domain tags
ALTER TABLE RAW_PRESCRIPTIONS SET TAG DATA_DOMAIN = 'COMMERCIAL';
ALTER TABLE RAW_HCP_PROFILES SET TAG DATA_DOMAIN = 'COMMERCIAL';
ALTER TABLE RAW_HCP_ENGAGEMENTS SET TAG DATA_DOMAIN = 'COMMERCIAL';
ALTER TABLE RX_METRICS_OUTPUT SET TAG DATA_DOMAIN = 'COMMERCIAL';
ALTER TABLE HCP_TIERED_PROFILES SET TAG DATA_DOMAIN = 'COMMERCIAL';
ALTER TABLE ENGAGEMENT_FINAL SET TAG DATA_DOMAIN = 'COMMERCIAL';

-- Data quality certification on target (golden) tables
ALTER TABLE RX_METRICS_OUTPUT SET TAG DATA_QUALITY_STATUS = 'CERTIFIED';
ALTER TABLE HCP_TIERED_PROFILES SET TAG DATA_QUALITY_STATUS = 'CERTIFIED';
ALTER TABLE ENGAGEMENT_FINAL SET TAG DATA_QUALITY_STATUS = 'CERTIFIED';
ALTER TABLE HCP_GOLDEN_RECORD SET TAG DATA_QUALITY_STATUS = 'CERTIFIED';

-- Source tables in review
ALTER TABLE RAW_PRESCRIPTIONS SET TAG DATA_QUALITY_STATUS = 'IN_REVIEW';
ALTER TABLE RAW_HCP_PROFILES SET TAG DATA_QUALITY_STATUS = 'IN_REVIEW';
ALTER TABLE RAW_HCP_ENGAGEMENTS SET TAG DATA_QUALITY_STATUS = 'IN_REVIEW';

-- Ownership
ALTER TABLE RX_METRICS_OUTPUT SET TAG DATA_OWNER = 'Commercial Analytics';
ALTER TABLE HCP_TIERED_PROFILES SET TAG DATA_OWNER = 'Medical Affairs';
ALTER TABLE ENGAGEMENT_FINAL SET TAG DATA_OWNER = 'Field Operations';

-- ============================================================
-- 3. Apply Tags to Sensitive Columns
-- ============================================================

-- PHI columns (Protected Health Information)
ALTER TABLE RAW_HCP_PROFILES MODIFY COLUMN HCP_NAME SET TAG SENSITIVITY_LEVEL = 'PHI';
ALTER TABLE RAW_HCP_PROFILES MODIFY COLUMN NPI_NUMBER SET TAG SENSITIVITY_LEVEL = 'PHI';
ALTER TABLE HCP_GOLDEN_RECORD MODIFY COLUMN HCP_NAME SET TAG SENSITIVITY_LEVEL = 'PHI';
ALTER TABLE HCP_GOLDEN_RECORD MODIFY COLUMN NPI_NUMBER SET TAG SENSITIVITY_LEVEL = 'PHI';

-- PII columns
ALTER TABLE RAW_HCP_ENGAGEMENTS MODIFY COLUMN REP_ID SET TAG SENSITIVITY_LEVEL = 'PII';
ALTER TABLE RAW_HCP_ENGAGEMENTS MODIFY COLUMN NOTES SET TAG SENSITIVITY_LEVEL = 'PII';

-- Public columns
ALTER TABLE DIM_DRUG MODIFY COLUMN DRUG_NAME SET TAG SENSITIVITY_LEVEL = 'PUBLIC';
ALTER TABLE DIM_DRUG MODIFY COLUMN BRAND_NAME SET TAG SENSITIVITY_LEVEL = 'PUBLIC';
ALTER TABLE DIM_TERRITORY MODIFY COLUMN TERRITORY_NAME SET TAG SENSITIVITY_LEVEL = 'PUBLIC';
ALTER TABLE DIM_REGION MODIFY COLUMN REGION_NAME SET TAG SENSITIVITY_LEVEL = 'PUBLIC';

-- ============================================================
-- 4. Masking Policy for NPI Numbers
-- ============================================================

CREATE OR REPLACE MASKING POLICY MASK_NPI_NUMBER AS (val VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('SYSADMIN', 'ACCOUNTADMIN') THEN val
        WHEN val IS NULL THEN NULL
        ELSE '***-***-' || RIGHT(val, 4)
    END;

-- Apply masking policy
ALTER TABLE RAW_HCP_PROFILES MODIFY COLUMN NPI_NUMBER
    SET MASKING POLICY MASK_NPI_NUMBER;
ALTER TABLE HCP_GOLDEN_RECORD MODIFY COLUMN NPI_NUMBER
    SET MASKING POLICY MASK_NPI_NUMBER;

-- ============================================================
-- 5. Masking Policy for HCP Names
-- ============================================================

CREATE OR REPLACE MASKING POLICY MASK_HCP_NAME AS (val VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('SYSADMIN', 'ACCOUNTADMIN') THEN val
        WHEN val IS NULL THEN NULL
        ELSE LEFT(val, 1) || '***' || ' ' || SPLIT_PART(val, ' ', -1)
    END;

ALTER TABLE RAW_HCP_PROFILES MODIFY COLUMN HCP_NAME
    SET MASKING POLICY MASK_HCP_NAME;
ALTER TABLE HCP_GOLDEN_RECORD MODIFY COLUMN HCP_NAME
    SET MASKING POLICY MASK_HCP_NAME;

-- ============================================================
-- 6. Masking Policy for Engagement Notes (free text may contain PHI)
-- ============================================================

CREATE OR REPLACE MASKING POLICY MASK_NOTES AS (val VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('SYSADMIN', 'ACCOUNTADMIN') THEN val
        ELSE '[REDACTED]'
    END;

ALTER TABLE RAW_HCP_ENGAGEMENTS MODIFY COLUMN NOTES
    SET MASKING POLICY MASK_NOTES;

-- ============================================================
-- 7. Verify Tags
-- ============================================================

SELECT *
FROM TABLE(INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS(
    'DEMO.HEALTHCARE_DEMO.RAW_HCP_PROFILES', 'TABLE'
));

SELECT *
FROM TABLE(INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS(
    'DEMO.HEALTHCARE_DEMO.HCP_GOLDEN_RECORD', 'TABLE'
));
