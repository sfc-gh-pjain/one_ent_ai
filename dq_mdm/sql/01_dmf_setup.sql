USE ROLE SYSADMIN;
USE WAREHOUSE MY_WH;
USE SCHEMA DEMO.HEALTHCARE_DEMO;

-- ============================================================
-- 1. Set Data Metric Schedule on Target Tables
-- ============================================================

ALTER TABLE RX_METRICS_OUTPUT SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';
ALTER TABLE HCP_TIERED_PROFILES SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';
ALTER TABLE ENGAGEMENT_FINAL SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';

ALTER TABLE RAW_PRESCRIPTIONS SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';
ALTER TABLE RAW_HCP_PROFILES SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';
ALTER TABLE RAW_HCP_ENGAGEMENTS SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';

-- ============================================================
-- 2. Attach Built-in DMFs to Target Tables
-- ============================================================

ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (DRUG_ID);
ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (METRIC_VALUE);
ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (DS, DRUG_ID, TERRITORY_ID, METRIC_NAME);
ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS ON (ETL_TIMESTAMP);

ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (HCP_ID);
ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (TIER);
ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (HCP_ID);
ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS ON (ETL_UPDATE_DATETIME_UTC);

ALTER TABLE ENGAGEMENT_FINAL ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (ENGAGEMENT_ID);
ALTER TABLE ENGAGEMENT_FINAL ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (HCP_ID);
ALTER TABLE ENGAGEMENT_FINAL ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (ENGAGEMENT_ID);

ALTER TABLE RAW_PRESCRIPTIONS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (RX_ID);
ALTER TABLE RAW_PRESCRIPTIONS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (DRUG_ID);
ALTER TABLE RAW_HCP_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (HCP_ID);
ALTER TABLE RAW_HCP_PROFILES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (NPI_NUMBER);
ALTER TABLE RAW_HCP_ENGAGEMENTS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (ENGAGEMENT_ID);

-- ============================================================
-- 3. Custom DMFs (using single-quote body for Snow CLI compatibility)
-- ============================================================

CREATE OR REPLACE DATA METRIC FUNCTION DMF_VALID_RX_VOLUME(
    ARG_T TABLE(METRIC_VALUE FLOAT)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T WHERE METRIC_VALUE <= 0 OR METRIC_VALUE IS NULL';

CREATE OR REPLACE DATA METRIC FUNCTION DMF_VALID_HCP_TIER(
    ARG_T TABLE(TIER VARCHAR)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T WHERE TIER NOT IN (''Tier 1'',''Tier 2'',''Tier 3'',''Tier 4'',''Tier 5'') OR TIER IS NULL';

CREATE OR REPLACE DATA METRIC FUNCTION DMF_VALID_HCP_DECILE(
    ARG_T TABLE(DECILE INTEGER)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T WHERE DECILE < 1 OR DECILE > 10 OR DECILE IS NULL';

CREATE OR REPLACE DATA METRIC FUNCTION DMF_NO_FUTURE_ENGAGEMENT_DATE(
    ARG_T TABLE(ENGAGEMENT_DATE DATE)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T WHERE ENGAGEMENT_DATE > CURRENT_DATE()';

CREATE OR REPLACE DATA METRIC FUNCTION DMF_RX_COMPLETENESS(
    ARG_T TABLE(DRUG_ID VARCHAR, TERRITORY_ID INTEGER, METRIC_VALUE FLOAT, DS VARCHAR)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T WHERE DRUG_ID IS NULL OR TERRITORY_ID IS NULL OR METRIC_VALUE IS NULL OR DS IS NULL';

CREATE OR REPLACE DATA METRIC FUNCTION DMF_RX_ORPHAN_DRUGS(
    ARG_T TABLE(DRUG_ID VARCHAR)
)
RETURNS NUMBER
AS
'SELECT COUNT(*) FROM ARG_T a WHERE NOT EXISTS (SELECT 1 FROM DEMO.HEALTHCARE_DEMO.DIM_DRUG d WHERE d.DRUG_ID = a.DRUG_ID)';

-- ============================================================
-- 4. Attach Custom DMFs to Tables
-- ============================================================

ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION DMF_VALID_RX_VOLUME ON (METRIC_VALUE);
ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION DMF_RX_COMPLETENESS ON (DRUG_ID, TERRITORY_ID, METRIC_VALUE, DS);
ALTER TABLE RX_METRICS_OUTPUT ADD DATA METRIC FUNCTION DMF_RX_ORPHAN_DRUGS ON (DRUG_ID);

ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION DMF_VALID_HCP_TIER ON (TIER);
ALTER TABLE HCP_TIERED_PROFILES ADD DATA METRIC FUNCTION DMF_VALID_HCP_DECILE ON (DECILE);

ALTER TABLE ENGAGEMENT_FINAL ADD DATA METRIC FUNCTION DMF_NO_FUTURE_ENGAGEMENT_DATE ON (ENGAGEMENT_DATE);

