-- Healthcare Demo: Schema and Table Setup
-- Domain: Commercial Medicine & Medical Products
-- Idempotent — safe to re-run

USE ROLE SYSADMIN;
USE WAREHOUSE MY_WH;

CREATE SCHEMA IF NOT EXISTS DEMO.HEALTHCARE_DEMO;
USE SCHEMA DEMO.HEALTHCARE_DEMO;

CREATE STAGE IF NOT EXISTS DEMO_STAGE;

-- ==========================================
-- Source Tables (raw ingested data)
-- ==========================================

CREATE OR REPLACE TABLE RAW_PRESCRIPTIONS (
    RX_ID VARCHAR(36),
    DRUG_ID VARCHAR(36),
    HCP_ID VARCHAR(36),
    TERRITORY_ID INTEGER,
    QUANTITY INTEGER,
    TOTAL_UNITS FLOAT,
    RX_DATE DATE,
    PAYER_TYPE VARCHAR(50),
    IS_NEW_PATIENT BOOLEAN,
    DS VARCHAR(10)
);

CREATE OR REPLACE TABLE RAW_HCP_PROFILES (
    HCP_ID VARCHAR(36),
    HCP_NAME VARCHAR(200),
    SPECIALTY VARCHAR(100),
    SUB_SPECIALTY VARCHAR(100),
    CREDENTIAL VARCHAR(20),
    NPI_NUMBER VARCHAR(20),
    TERRITORY_ID INTEGER,
    THERAPEUTIC_AREA_ID INTEGER,
    PRACTICE_TYPE VARCHAR(50),
    YEARS_EXPERIENCE INTEGER,
    CREATED_AT TIMESTAMP_NTZ,
    ETL_UPDATE_DATETIME_UTC TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE RAW_HCP_ENGAGEMENTS (
    ENGAGEMENT_ID VARCHAR(36),
    HCP_ID VARCHAR(36),
    REP_ID VARCHAR(36),
    DRUG_ID VARCHAR(36),
    ENGAGEMENT_TYPE VARCHAR(50),
    CHANNEL VARCHAR(50),
    ENGAGEMENT_DATE DATE,
    DURATION_MINUTES INTEGER,
    SAMPLES_DROPPED INTEGER,
    NOTES VARCHAR(500),
    SENTIMENT_SCORE FLOAT,
    UPDATED_AT TIMESTAMP_NTZ
);

-- ==========================================
-- Dimension Tables
-- ==========================================

CREATE OR REPLACE TABLE DIM_DRUG (
    DRUG_ID VARCHAR(36),
    DRUG_NAME VARCHAR(200),
    BRAND_NAME VARCHAR(200),
    GENERIC_NAME VARCHAR(200),
    THERAPEUTIC_AREA VARCHAR(100),
    INDICATION VARCHAR(200),
    DOSAGE_FORM VARCHAR(50),
    LAUNCH_DATE DATE,
    IS_SPECIALTY BOOLEAN,
    ANNUAL_REVENUE_MM FLOAT
);

CREATE OR REPLACE TABLE DIM_TERRITORY (
    TERRITORY_ID INTEGER,
    TERRITORY_NAME VARCHAR(100),
    TERRITORY_KEY VARCHAR(36),
    DISTRICT_NAME VARCHAR(100),
    REGION_ID INTEGER
);

CREATE OR REPLACE TABLE DIM_REGION (
    REGION_ID INTEGER,
    REGION_NAME VARCHAR(100),
    REGION_KEY VARCHAR(36),
    COUNTRY VARCHAR(50)
);

CREATE OR REPLACE TABLE DIM_THERAPEUTIC_AREA (
    THERAPEUTIC_AREA_ID INTEGER,
    AREA_NAME VARCHAR(100),
    AREA_KEY VARCHAR(36),
    DISEASE_CATEGORY VARCHAR(100)
);

-- ==========================================
-- Target Tables (pipeline outputs)
-- ==========================================

CREATE OR REPLACE TABLE RX_METRICS_OUTPUT (
    DS VARCHAR(10),
    METRIC_NAME VARCHAR(100),
    PERIOD_GRAIN VARCHAR(20),
    DRUG_ID VARCHAR(36),
    TERRITORY_ID INTEGER,
    METRIC_VALUE FLOAT,
    ETL_TIMESTAMP TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE HCP_TIERED_PROFILES (
    HCP_ID VARCHAR(36),
    SPECIALTY VARCHAR(100),
    STANDARDIZED_SPECIALTY VARCHAR(100),
    SPECIALTY_GROUP_ID INTEGER,
    TIER VARCHAR(20),
    DECILE INTEGER,
    CONFIDENCE FLOAT,
    ETL_UPDATE_DATETIME_UTC TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE ENGAGEMENT_FINAL (
    ENGAGEMENT_ID VARCHAR(36),
    HCP_ID VARCHAR(36),
    REP_ID VARCHAR(36),
    DRUG_NAME VARCHAR(200),
    THERAPEUTIC_AREA VARCHAR(100),
    TERRITORY_KEY VARCHAR(36),
    REGION_KEY VARCHAR(36),
    AREA_KEY VARCHAR(36),
    ENGAGEMENT_TYPE VARCHAR(50),
    CHANNEL VARCHAR(50),
    DURATION_MINUTES INTEGER,
    SAMPLES_DROPPED INTEGER,
    ENGAGEMENT_DATE DATE
);
