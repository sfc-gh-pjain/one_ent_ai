#!/bin/bash
# stop_all.sh — Stop everything: Airflow + Snowflake Tasks + DTs
# Run as: ./stop_all.sh
# Requires: SYSADMIN role (ACCOUNTADMIN DTs will be skipped with warning)

set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "============================================"
echo "  STOPPING ALL DEMO SERVICES"
echo "============================================"

# --- 1. Stop Airflow ---
echo ""
echo "[1/3] Stopping Airflow..."
if pgrep -f "airflow" > /dev/null 2>&1; then
  pkill -f "airflow" 2>/dev/null || true
  sleep 2
  pkill -9 -f "airflow" 2>/dev/null || true
  echo "  Airflow stopped."
else
  echo "  Airflow not running."
fi

# --- 2. Suspend Healthcare Demo Tasks ---
echo ""
echo "[2/3] Suspending HEALTHCARE_DEMO tasks..."
snow sql --silent -c my_conn -q "
ALTER TASK IF EXISTS DEMO.HEALTHCARE_DEMO.TASK_MDM_HCP_DEDUP SUSPEND;
ALTER TASK IF EXISTS DEMO.HEALTHCARE_DEMO.TASK_MDM_RX_OUTLIER_DETECTION SUSPEND;
ALTER TASK IF EXISTS DEMO.HEALTHCARE_DEMO.TASK_MDM_ENGAGEMENT_VALIDATION SUSPEND;
ALTER TASK IF EXISTS DEMO.HEALTHCARE_DEMO.TASK_MDM_TIER_VALIDATION SUSPEND;
" 2>/dev/null && echo "  Healthcare tasks suspended." || echo "  Warning: some tasks may have failed to suspend."

# --- 3. Suspend ALL Dynamic Tables (SYSADMIN-owned) ---
echo ""
echo "[3/3] Suspending Dynamic Tables..."
snow sql --silent -c my_conn -q "
ALTER DYNAMIC TABLE IF EXISTS DEMO.STATION_METRICS.FACT_STATION_METRICS SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.STATION_METRICS.SILVER_STATION_EVENTS SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.EMAIL_DEMO.EMAIL_LIVE SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.EMAIL_DEMO.STG_EMAIL_DT SUSPEND;
" 2>/dev/null && echo "  SYSADMIN-owned DTs suspended." || echo "  Warning: some DTs may have failed."

# Attempt ACCOUNTADMIN-owned DTs (will fail gracefully if no access)
snow sql --silent -c my_conn -q "
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_DEMO.CUMULATIVE_PURCHASE SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_DEMO.CUSTOMER_SALES_DATA_HISTORY SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_DEMO.MY_DYNAMIC_TABLE SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_DEMO.PROD_INV_ALERT SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_DEMO.SALESREPORT SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_DAILY_SALES_ROLLING SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_EXECUTIVE_DASHBOARD SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_FISCAL_PERIOD_SALES SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_INVENTORY_ENRICHED SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_LOW_STOCK_ALERTS SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_MONTHLY_SALES_CLOSED SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_SALES_BY_DEPARTMENT_24H SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_SALES_ENRICHED SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.DT_PIPELINE.DT_TOP_PRODUCTS_24H SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.STREAMING.CUSTOMER_HISTORY SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.STREAMING.CUSTOMER_HISTORY_LOCAL SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.STREAMING.CUSTOMER_LATEST SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS DEMO.STREAMING.CUSTOMER_LATEST_LOCAL SUSPEND;
" 2>/dev/null && echo "  ACCOUNTADMIN-owned DTs suspended." || echo "  Warning: ACCOUNTADMIN DTs require elevated role (run in Snowsight as ACCOUNTADMIN)."

# Also suspend other active tasks not from our demo
snow sql --silent -c my_conn -q "
ALTER TASK IF EXISTS DEMO.DATA_ENG.TASK_REGULAR SUSPEND;
ALTER TASK IF EXISTS DEMO.DATA_ENG.TASK_SERVERLESS SUSPEND;
ALTER TASK IF EXISTS DEMO.STATION_METRICS_STP.TASK_LOAD_SILVER SUSPEND;
ALTER TASK IF EXISTS DEMO.STATION_METRICS_STP.TASK_LOAD_FACT SUSPEND;
ALTER TASK IF EXISTS DEMO.TEST.LOAD_NEW_CSV_DATA SUSPEND;
" 2>/dev/null && echo "  Other active tasks suspended." || echo "  Warning: some tasks may require ACCOUNTADMIN."

echo ""
echo "============================================"
echo "  ALL STOPPED"
echo "============================================"
echo ""
echo "To verify: snow sql -q \"SELECT 'TASKS' as type, COUNT(*) as active FROM (SHOW TASKS IN DATABASE DEMO) WHERE \\\"state\\\" = 'started'\""
